# --- Generic convenience -------------------------------------------------

#: A small but commonly-used subset (extracted by name into a single
#: dict for fast lookup from error-handling code).
WIN32_ERROR_NAMES: Dict[int, str] = {
    v: k
    for k, v in globals().items()
    if k.startswith("ERROR_") and isinstance(v, int)
}


def format_win32_error(err: int) -> str:
    """Return a human-readable label for a Win32 error code (or hex fallback)."""
    name = WIN32_ERROR_NAMES.get(err)
    if name is not None:
        return f"{name} (0x{err:08X})"
    return f"0x{err:08X}"


def format_hresult(hr: int) -> str:
    """Return a human-readable label for an HRESULT."""
    if hr == S_OK:
        return "S_OK"
    if hr == S_FALSE:
        return "S_FALSE"
    if hr == E_NOTIMPL:
        return "E_NOTIMPL"
    if hr == E_POINTER:
        return "E_POINTER"
    if hr == E_INVALIDARG:
        return "E_INVALIDARG"
    if hr == E_OUTOFMEMORY:
        return "E_OUTOFMEMORY"
    if hr == E_FAIL:
        return "E_FAIL"
    if (hr & HRESULT_FROM_WIN32) == HRESULT_FROM_WIN32:
        win = hr & 0xFFFF
        return f"HRESULT_FROM_WIN32({format_win32_error(win)})"
    fac = facility(hr) >> 16
    code = hr & 0xFFFF
    return f"HRESULT(facility=0x{fac:04X}, code=0x{code:04X})"
