"""
Umer OS /compatibility/winerror — Windows error codes
=====================================================

The Microsoft Windows error model exposes two parallel code spaces:

* ``HRESULT``  (32-bit, returned by COM / WinRT and the higher-layer
  Win32 API).  Severity bits in the top word: ``SEVERITY_ERROR``
  (``0x80000000``) for failures, ``SEVERITY_SUCCESS`` (``0x00000000``)
  for success.

* ``LSTATUS`` / ``GetLastError()`` (32-bit "Win32" error code, returned
  by most C-style Win32 calls in kernel32 / user32 / advapi32 / etc.).
  ``winerror.h`` is the canonical source.

This module is a pure-Python reference of the most commonly-seen
values, designed to be imported by Umer OS's pure-Python Windows
compatibility layer.  Where a value depends on the Windows SDK
version we pick the longest-standing definition; where the value is
missing we return ``ERROR_SUCCESS`` / ``S_OK`` rather than guessing.

References
----------

* https://learn.microsoft.com/en-us/windows/win32/seccrypto/common-hresult-values
* https://learn.microsoft.com/en-us/windows/win32/debug/system-error-codes
* https://learn.microsoft.com/en-us/openspecs/windows_protocols/ms-erref

Author:  Umer OS Project
Licence: GPL-3.0
"""

from __future__ import annotations

# ---------------------------------------------------------------------------
# Severity / facility helpers
# ---------------------------------------------------------------------------

SEVERITY_SUCCESS = 0x00000000
SEVERITY_ERROR = 0x80000000
SEVERITY_MASK = 0xC0000000  # both bits set = "WIN32" error category
FACILITY_MASK = 0x0FFF0000


def severity(hr: int) -> int:
    """Return the severity bits of an HRESULT."""
    return hr & SEVERITY_MASK


def facility(hr: int) -> int:
    """Return the facility bits of an HRESULT."""
    return hr & FACILITY_MASK


def make_hresult(facility: int, code: int) -> int:
    """Build an HRESULT with the given facility and error code."""
    severity_bits = SEVERITY_ERROR if code else SEVERITY_SUCCESS
    return severity_bits | (facility << 16) | (code & 0xFFFF)


def failed(hr: int) -> bool:
    """Return True if the HRESULT indicates failure (SEVERITY_ERROR set)."""
    return (hr & SEVERITY_ERROR) != 0


