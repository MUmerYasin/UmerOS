# ---------------------------------------------------------------------------
# Result Types
# ---------------------------------------------------------------------------

@dataclass
class RandomBit:
    """A single random bit."""
    value: int
    circuit_depth: int
    basis: str = "computational"

    def __int__(self) -> int:
        return self.value

    def __bool__(self) -> bool:
        return bool(self.value)

    def __repr__(self) -> str:
        return f"RandomBit({self.value})"


@dataclass
class RandomBytes:
    """Random byte sequence."""
    data: bytes
    num_bits: int
    method: str

    def hex(self) -> str:
        return self.data.hex()

    def int(self) -> int:
        return int.from_bytes(self.data, 'big')

    def bits(self) -> List[int]:
        return [int(b) for b in format(self.int(), f'0{self.num_bits}b')]

    def __len__(self) -> int:
        return len(self.data)

    def __repr__(self) -> str:
        return f"RandomBytes({len(self.data)} bytes, method={self.method})"


# ---------------------------------------------------------------------------
# Core QRNG
# ---------------------------------------------------------------------------

class QRNG:
    """Quantum Random Number Generator.

    Uses quantum circuits to generate true random numbers
    based on quantum mechanical principles.
    """

    def __init__(self, backend: Optional[LocalBackend] = None,
                 seed: Optional[int] = None):
        """Initialize QRNG.

        Args:
            backend: Optional backend for simulation
            seed: Optional seed for reproducibility
        """
        self._backend = backend
        self._seed = seed
        self._count = 0

    def _run_circuit(self, circuit: QuantumCircuit) -> dict:
        """Run a circuit and return measurement results."""
        backend = self._backend or LocalBackend()
        result = backend.run(circuit, shots=1)
        return result.counts

    def random_bit(self) -> RandomBit:
        """Generate a single random bit.

        Returns:
            RandomBit with 0 or 1
        """
        qr = QuantumRegister(1, "q")
        cr = ClassicalRegister(1, "c")
        circuit = QuantumCircuit(qr, cr)

        # Create superposition
        circuit.h(qr[0])
        circuit.measure(qr[0], cr[0])

        counts = self._run_circuit(circuit)
        bit = int(list(counts.keys())[0], 2)
        self._count += 1

        return RandomBit(
            value=bit,
            circuit_depth=circuit.depth,
            basis="computational"
        )

    def random_bits(self, n: int) -> List[int]:
        """Generate multiple random bits.

        Args:
            n: Number of bits to generate

        Returns:
            List of random bits
        """
        bits = []
        for _ in range(n):
            bits.append(self.random_bit().value)
        return bits

    def random_int(self, bits: int = 32) -> int:
        """Generate a random integer.

        Args:
            bits: Number of bits for the integer

        Returns:
            Random integer
        """
        random_bits = self.random_bits(bits)
        result = 0
        for bit in random_bits:
            result = (result << 1) | bit
        return result

    def random_float(self) -> float:
        """Generate a random float between 0 and 1.

        Returns:
            Random float in [0, 1)
        """
        # Use 64 bits for precision
        random_bits = self.random_bits(64)
        value = 0
        for bit in random_bits:
            value = (value << 1) | bit
        return value / (2 ** 64)

    def random_bytes(self, num_bytes: int) -> RandomBytes:
        """Generate random bytes.

        Args:
            num_bytes: Number of bytes to generate

        Returns:
            RandomBytes with the generated bytes
        """
        byte_array = bytearray()
        for _ in range(num_bytes):
            byte_bits = self.random_bits(8)
            byte_val = 0
            for bit in byte_bits:
                byte_val = (byte_val << 1) | bit
            byte_array.append(byte_val)

        self._count += num_bytes * 8

        return RandomBytes(
            data=bytes(byte_array),
            num_bits=num_bytes * 8,
            method="quantum_hadamard"
        )

    def random_string(self, length: int) -> str:
        """Generate a random alphanumeric string.

        Args:
            length: Length of the string

        Returns:
            Random alphanumeric string
        """
        chars = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789"
        indices = [self.random_int(6) % len(chars) for _ in range(length)]
        return "".join(chars[i] for i in indices)

    def coin_flip(self) -> bool:
        """Simulate a fair coin flip.

        Returns:
            True or False
        """
        return bool(self.random_bit().value)


