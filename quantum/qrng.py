def test_randomness_bias(bits: List[int], confidence: float = 0.05) -> dict:
    """Test for bias in random bit sequence.

    Args:
        bits: List of random bits (0s and 1s)
        confidence: Confidence level for test

    Returns:
        Dictionary with test results
    """
    n = len(bits)
    if n == 0:
        return {"error": "No bits provided"}

    ones = sum(bits)
    zeros = n - ones
    ratio = ones / n

    # Expected ratio under null hypothesis
    expected_ratio = 0.5
    expected_ones = n * expected_ratio

    # Chi-square test
    chi_square = ((ones - expected_ones) ** 2 / expected_ones +
                  (zeros - expected_ones) ** 2 / expected_ones)

    # Simple threshold (chi-square with 1 df)
    threshold = 3.841

    return {
        "num_bits": n,
        "num_ones": ones,
        "num_zeros": zeros,
        "ratio": ratio,
        "chi_square": chi_square,
        "threshold": threshold,
        "is_random": chi_square < threshold,
        "bias": abs(ratio - 0.5),
    }


def test_entropy_rate(bits: List[int], block_size: int = 8) -> dict:
    """Estimate entropy rate of bit sequence.

    Args:
        bits: List of random bits
        block_size: Block size for analysis

    Returns:
        Dictionary with entropy estimates
    """
    n = len(bits)
    if n < block_size:
        return {"error": "Not enough bits"}

    # Count unique blocks
    blocks = {}
    for i in range(0, n - block_size + 1, block_size):
        block = tuple(bits[i:i + block_size])
        blocks[block] = blocks.get(block, 0) + 1

    num_blocks = len(blocks)
    total_blocks = sum(blocks.values())

    # Calculate Shannon entropy
    entropy = 0.0
    for count in blocks.values():
        p = count / total_blocks
        if p > 0:
            entropy -= p * math.log2(p)

    max_entropy = math.log2(num_blocks) if num_blocks > 0 else 0

    return {
        "num_bits": n,
        "block_size": block_size,
        "unique_blocks": num_blocks,
        "entropy_per_block": entropy,
        "entropy_per_bit": entropy / block_size,
        "max_entropy_per_bit": max_entropy / block_size,
        "efficiency": entropy / max_entropy if max_entropy > 0 else 0,
    }


