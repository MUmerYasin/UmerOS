def generate_random_bit(backend: Optional[LocalBackend] = None) -> bool:
    """Generate a single random bit.

    Args:
        backend: Optional backend

    Returns:
        True or False
    """
    qrng = QRNG(backend)
    return qrng.coin_flip()


def generate_random_int(bits: int = 32,
                        backend: Optional[LocalBackend] = None) -> int:
    """Generate a random integer.

    Args:
        bits: Number of bits
        backend: Optional backend

    Returns:
        Random integer
    """
    qrng = QRNG(backend)
    return qrng.random_int(bits)


