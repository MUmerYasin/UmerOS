"""
Umer OS Initrd Scenarios
========================
The four "usage scenarios" from the TLDP ``/initrd`` reference, plus a
fifth one (``per_machine``) that maps directly to the second TLDP
motivation ("different hardware configurations in a single
administrative domain").

Each scenario is a self-contained :class:`InitrdScenario` that owns:

* A description (shown to the user via the GUI / CLI).
* A list of "things this scenario must do" (file creation, module
  loading, hook installation, AI hints).
* An entry-point coroutine that the :mod:`initrd.linuxrc` runner
  calls once the initrd has been mounted as root.

Scenarios are pure data: they never touch the VFS or the phase
machine directly.  That keeps them easy to unit-test in isolation.

Author:  Umer OS Project
Licence: Apache 2.0
"""

from __future__ import annotations

import logging
from dataclasses import dataclass, field
from enum import Enum
from typing import Any, Awaitable, Callable, Dict, List, Optional

from initrd.cpio import CpioEntry, newc_dir, newc_file, newc_symlink
from initrd.module_resolver import ModuleResolver, ModuleSpec, ModuleReason

log = logging.getLogger("UmerOS.Initrd.Scenarios")


# ---------------------------------------------------------------------------
# Built-in scenario IDs
# ---------------------------------------------------------------------------

class ScenarioId(str, Enum):
    """The five scenarios that ship with Umer OS."""

    NORMAL     = "normal"       # Plain boot: load modules, mount, pivot.
    INSTALL    = "install"      # First-boot: detect media, set up /, write image.
    RECOVERY   = "recovery"     # Damaged real root: drop to a rescue shell.
    LIVE       = "live"         # Live CD: keep initrd as final root.
    RESCUE     = "rescue"       # No real root - stay in the initrd shell.
    PER_MACHINE = "per_machine" # Per-machine config layered on top of NORMAL.


# ---------------------------------------------------------------------------
# Scenario dataclass
# ---------------------------------------------------------------------------

@dataclass
class InitrdScenario:
    """A pre-canned ``/linuxrc`` strategy."""

    id: ScenarioId
    title: str
    description: str
    extra_modules: List[str] = field(default_factory=list)
    extra_files: Dict[str, bytes] = field(default_factory=dict)
    extra_directories: List[str] = field(default_factory=list)
    extra_symlinks: Dict[str, str] = field(default_factory=dict)
    extra_hooks: Dict[str, List[str]] = field(default_factory=dict)
    keep_as_root: bool = False
    interactive: bool = False
    notes: List[str] = field(default_factory=list)

    def resolve_modules(self, resolver: ModuleResolver) -> List[ModuleSpec]:
        """Add this scenario's modules to ``resolver`` and return them."""
        specs: List[ModuleSpec] = []
        for name in self.extra_modules:
            spec = resolver._lookup(name)  # noqa: SLF001 - intentional
            if spec is None:
                log.warning("scenario %s: unknown module %s", self.id.value, name)
                continue
            tagged = ModuleSpec(
                name=spec.name,
                reason=ModuleReason.SCENARIO,
                parameters=dict(spec.parameters),
                dependencies=list(spec.dependencies),
                source=f"scenario:{self.id.value}",
            )
            resolver.selected[tagged.name] = tagged
            specs.append(tagged)
        return specs

    def build_entries(self, base_entries: List[CpioEntry]) -> List[CpioEntry]:
        """Return ``base_entries`` plus this scenario's extra files."""
        out: List[CpioEntry] = list(base_entries)
        ino = 1000 + len(out)
        # Directories
        for d in self.extra_directories:
            out.append(newc_dir(d, ino=ino))
            ino += 1
        # Files
        for path, data in self.extra_files.items():
            out.append(newc_file(path, data=data, ino=ino))
            ino += 1
        # Symlinks
        for src, target in self.extra_symlinks.items():
            out.append(newc_symlink(src, target, ino=ino))
            ino += 1
        return out


