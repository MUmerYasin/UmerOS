def get_scenario(sid: ScenarioId) -> InitrdScenario:
    """Return the built-in scenario for ``sid`` (raises if unknown)."""
    if sid not in SCENARIO_CATALOGUE:
        raise KeyError(f"unknown scenario: {sid}")
    return SCENARIO_CATALOGUE[sid]


def list_scenarios() -> List[ScenarioId]:
    return list(SCENARIO_CATALOGUE.keys())


# ---------------------------------------------------------------------------
# Scenario runner
# ---------------------------------------------------------------------------

class ScenarioRunner:
    """Executes a scenario against the live :mod:`initrd.linuxrc` state."""

    def __init__(self, scenario: InitrdScenario) -> None:
        self.scenario = scenario

    def apply_modules(self, resolver: ModuleResolver) -> List[ModuleSpec]:
        return self.scenario.resolve_modules(resolver)

    def apply_files(self, entries: List[CpioEntry]) -> List[CpioEntry]:
        return self.scenario.build_entries(entries)

    def should_keep_as_root(self) -> bool:
        return self.scenario.keep_as_root

    def summary(self) -> Dict[str, Any]:
        return {
            "id":          self.scenario.id.value,
            "title":       self.scenario.title,
            "interactive": self.scenario.interactive,
            "modules":     list(self.scenario.extra_modules),
            "files":       list(self.scenario.extra_files),
            "directories": list(self.scenario.extra_directories),
            "symlinks":    dict(self.scenario.extra_symlinks),
            "hooks":       {k: list(v) for k, v in self.scenario.extra_hooks.items()},
            "notes":       list(self.scenario.notes),
        }


# ---------------------------------------------------------------------------
# Self-test
# ---------------------------------------------------------------------------

def _selftest() -> bool:
    s = get_scenario(ScenarioId.NORMAL)
    if "ext4" not in s.extra_modules:
        return False
    r = ModuleResolver()
    s.resolve_modules(r)
    if "ext4" not in r.selected:
        return False
    entries = s.build_entries([])
    # Cpio entries keep the leading "/" from the path.
    has_hostname = any(e.name == "/etc/hostname" for e in entries)
    return has_hostname


if __name__ == "__main__":
    logging.basicConfig(level=logging.INFO)
    print("scenarios selftest:", "OK" if _selftest() else "FAIL")
